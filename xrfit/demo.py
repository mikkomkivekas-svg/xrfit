"""Synthetic example spectrum (Fe, Cu, Zn, Pb-L on a Si detector) used by the web UI and docs."""
import numpy as np

from . import core

TRUE_AREAS = {"Fe-K": 40000.0, "Cu-K": 15000.0, "Zn-K": 8000.0, "Pb-L": 5000.0}


def synthetic_spectrum(seed=1):
    cfg = core.Config(elements=["Fe", "Cu", "Zn", "Pb-L"], zero=0.02, gain=0.01, noise=0.12,
                      tail_frac=0.05, esc_frac=0.01)
    ch = np.arange(2048.0)
    p = cfg.params()
    A, names, _ = core.design(cfg, p, ch)
    amp = np.array([TRUE_AREAS[n] for n in names])
    e = p["zero"] + p["gain"] * ch
    rng = np.random.default_rng(seed)
    y = rng.poisson(A @ amp + 150 * np.exp(-e / 6) + 5)
    meta = {"_format": "synthetic example", "Sample.Name": "Synthetic Fe / Cu / Zn / Pb-L",
            "Sample.Note": "Generated by xrfit; true values are listed below",
            "Truth.Calibration zero (keV)": 0.02, "Truth.Calibration gain (keV/channel)": 0.01,
            "Truth.Noise FWHM (keV)": 0.12, "Truth.Tail fraction": 0.05, "Truth.Escape fraction": 0.01,
            **{f"Truth.Net counts {k}": v for k, v in TRUE_AREAS.items()}}
    return core.Spectrum(y.astype(float), "synthetic-example.txt", live_time=100.0, calib=None, meta=meta)


